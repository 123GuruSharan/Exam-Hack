let currentQuestion = 0;
const answers = Array(questions.length).fill(null);

const questionText = document.getElementById("questionText");
const optionsContainer = document.getElementById("options");
const questionNumbers = document.getElementById("questionNumbers");
const submitBtn = document.getElementById("submitBtn");
const validationMessage = document.getElementById("validationMessage");
const timerEl = document.getElementById("timer");

function renderQuestion() {
  const data = questions[currentQuestion];

  document.querySelector(".question-panel").classList.toggle(
    "passage-question",
    data.type === "passage"
  );
  document.querySelector(".question-panel").classList.toggle(
    "cse-question",
    data.type === "cse"
  );

  document.querySelector(".options-panel").classList.toggle(
    "passage-options",
    data.type === "passage"
  );

  document.querySelector(".instruction").textContent = data.instruction;

  if (data.type === "passage") {
    questionText.innerHTML = `
      <div class="passage-label">PASSAGE</div>
      <div class="passage-text">${data.passage}</div>
    `;
  } else {
    questionText.innerHTML = data.question;
  }

  const staticOptionsHeading = document.querySelector(".options-panel > .options-heading");
  if (staticOptionsHeading) {
    staticOptionsHeading.textContent = "OPTIONS";
  }

  optionsContainer.innerHTML = "";

  if (data.type === "passage") {
    const instructionEl = document.createElement("div");
    instructionEl.className = "passage-instruction";
    instructionEl.textContent = data.instruction;
    optionsContainer.appendChild(instructionEl);

    const prompt = document.createElement("div");
    prompt.className = "passage-prompt";
    prompt.textContent = data.question;
    optionsContainer.appendChild(prompt);

    const optionsHead = document.createElement("div");
    optionsHead.className = "options-heading-inner";
    optionsHead.textContent = "OPTIONS";
    optionsContainer.appendChild(optionsHead);
  }

  data.options.forEach((optionText, index) => {
    const option = document.createElement("div");
    option.className = "option";
    if (answers[currentQuestion] === index) option.classList.add("selected");

    option.textContent = optionText;
    option.addEventListener("click", () => {
      answers[currentQuestion] = index;
      validationMessage.textContent = "";
      validationMessage.classList.remove("visible");
      renderQuestion();
    });

    optionsContainer.appendChild(option);
  });

  [...questionNumbers.children].forEach((el, index) => {
    el.classList.toggle("active", index === currentQuestion);
    el.classList.toggle("answered", answers[index] !== null && index !== currentQuestion);
  });

  const codingSimBtn = document.getElementById("codingSimBtn");
  if (codingSimBtn) {
    if (currentQuestion === 49) {
      codingSimBtn.classList.add("enabled");
    } else {
      codingSimBtn.classList.remove("enabled");
    }
  }
}

function renderNavigation() {
  questionNumbers.innerHTML = "";

  questions.forEach((_, index) => {
    const number = document.createElement("button");
    number.className = "question-number";
    number.textContent = index + 1;
    number.setAttribute("aria-label", `Question ${index + 1}`);
    number.addEventListener("click", () => {
      currentQuestion = index;
      renderQuestion();
    });
    questionNumbers.appendChild(number);
  });
}

let totalSeconds = 30 * 60;
let timerInterval = null;

function formatMMSS(secs) {
  const clamped = Math.max(0, secs);
  const minutes = Math.floor(clamped / 60);
  const seconds = clamped % 60;
  return `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}

function updateTimer() {
  if (timerEl) {
    timerEl.textContent = formatMMSS(totalSeconds);
  }
  if (totalSeconds <= 0) {
    if (timerInterval) {
      clearInterval(timerInterval);
      timerInterval = null;
    }
    return;
  }
  totalSeconds--;
}

function startTimer() {
  if (timerInterval) {
    clearInterval(timerInterval);
    timerInterval = null;
  }
  updateTimer();
  timerInterval = setInterval(updateTimer, 1000);
}

window.addEventListener("beforeunload", () => {
  if (timerInterval) {
    clearInterval(timerInterval);
    timerInterval = null;
  }
});

